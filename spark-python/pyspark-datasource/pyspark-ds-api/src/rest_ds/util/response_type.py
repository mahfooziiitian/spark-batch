# application/json – Most common for REST APIs. Data is returned in JSON format.
# application/xml – Used for XML data. Less common than JSON.
# text/html – Used for HTML data. Common for web pages.
# text/plain – Used for plain text data. Rarely used in APIs.
# application/x-www-form-urlencoded – Used for form submissions. Data is encoded in key-value pairs.
# multipart/form-data – Used for file uploads. Data is sent in multiple parts.
# application/octet-stream – Used for binary data. Common for file downloads.
